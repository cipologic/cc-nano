HAT_LINES: dict[str, str] = {
    "none": "",
    "crown": "   \\^^^/    ",
    "tophat": "   [___]    ",
    "propeller": "    -+-     ",
    "halo": "   (   )    ",
    "wizard": "    /^\\     ",
    "beanie": "   (___)    ",
    "tinyduck": "    ,>      ",
}

# ---------------------------------------------------------------------------
# 渲染函数
# ---------------------------------------------------------------------------


def render_sprite(bones: CompanionBones, frame: int = 0) -> list[str]:
    """根据给定的伙伴骨骼和动画帧渲染精灵图。

    移植自 sprites.ts 中的 renderSprite()。
    """
    frames = BODIES[bones.species]
    body = frames[frame % len(frames)]
    lines = [line.replace("{E}", bones.eye) for line in body]

    # 如果第 0 行为空且帽子不是 'none'，则替换帽子行
    if bones.hat != "none" and not lines[0].strip():
        lines[0] = HAT_LINES[bones.hat]

    # 如果所有帧的第 0 行均为空，则移除空白的帽子槽位行
    if not lines[0].strip() and all(not f[0].strip() for f in frames):
        lines = lines[1:]

    return lines


def sprite_frame_count(species: str) -> int:
    return len(BODIES[species])


def render_face(bones: CompanionBones) -> str:
    """渲染伙伴的紧凑单行面部表情。

    移植自 sprites.ts 中的 renderFace()。
    """
    e = bones.eye
    s = bones.species
    if s in ("duck", "goose"):
        return f"({e}>)"
    if s == "blob":
        return f"({e}{e})"
    if s == "cat":
        return f"={e}\u03c9{e}="
    if s == "dragon":
        return f"<{e}~{e}>"
    if s == "octopus":
        return f"~({e}{e})~"
    if s == "owl":
        return f"({e})({e})"
    if s == "penguin":
        return f"({e}>)"
    if s == "turtle":
        return f"[{e}_{e}]"
    if s == "snail":
        return f"{e}(@)"
    if s == "ghost":
        return f"/{e}{e}\\"
    if s == "axolotl":
        return f"}}{e}.{e}{{"
    if s == "capybara":
        return f"({e}oo{e})"
    if s == "cactus":
        return f"|{e}  {e}|"
    if s == "robot":
        return f"[{e}{e}]"
    if s == "rabbit":
        return f"({e}..{e})"
    if s == "mushroom":
        return f"|{e}  {e}|"
    if s == "chonk":
        return f"({e}.{e})"
    if s == "pikachu":
        return "⠸⣠⡶⠄⡠⢶⡄⠸"
    return f"({e}{e})"
